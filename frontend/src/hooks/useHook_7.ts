import { useState, useEffect } from 'react';
export function useHook7(initial: number) {
  const [val,setVal]=useState(initial);
  const [history,setHistory]=useState<number[]>([]);
  useEffect(()=>{ setHistory(h=>[...h,val].slice(-10)); },[val]);
  const inc=()=>setVal(v=>v+1); const dec=()=>setVal(v=>v-1); const reset=()=>setVal(initial);
  const isEven=val%2===0; const isPrime=()=>{ if(val<=1) return false; for(let i=2;i*i<=val;i++) if(val%i===0) return false; return true; };
  return {val,history,inc,dec,reset,isEven,isPrime};
}
